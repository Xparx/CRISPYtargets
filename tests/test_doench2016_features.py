"""Feature-extraction regression tests for Doench 2016 Rule Set 2.

Pins the feature contract of crispy/doench2016.py: 30mer assembly
(5bp 5' flank + 20bp guide + PAM + 2bp 3' flank), block order and lengths,
GC and NGGX feature slots, melting-temperature segments, and use of the
actual PAM. Guards the historical bug classes fixed in commits
a3d3b4d (real flanks), 1c6685d (actual PAM), 1dc3fe9 (Tm features, GC
reorder), and 0f35f9b (score fix).

Golden scores in fixtures/doench2016_scores.tsv were generated by
fixtures/regenerate_doench2016_scores.py and depend on the biopython
version recorded in the fixture header (Tm_NN feeds 4 feature slots).
"""

from itertools import product
from pathlib import Path

import numpy as np
import pytest

import crispytargets.design.doench2016 as doench2016

FIXTURE_PATH = Path(__file__).parent / "fixtures" / "doench2016_scores.tsv"

# The nucleotide alphabet order is part of the feature contract:
# every one-hot block is indexed by itertools.product(ALPHABET, ...).
# Changing it changes every score, so it is pinned here independently
# of the implementation's RAW_ALPHABET.
ALPHABET = ("A", "T", "C", "G")

# Block layout of the 627-feature vector, in order.
PD1 = slice(0, 120)      # order-1 position-dependent:  4 * 30
PI1 = slice(120, 124)    # order-1 position-independent: 4
PD2 = slice(124, 588)    # order-2 position-dependent:  16 * 29
PI2 = slice(588, 604)    # order-2 position-independent: 16
GC = slice(604, 607)     # [gc > 10, gc < 10, gc]
NGGX = slice(607, 623)   # one-hot of s[24] + s[27]
TM = slice(623, 627)     # Tm_NN of 30mer and three sub-segments


def kmers(order):
    """Independent reimplementation of the documented one-hot ordering."""
    return ["".join(p) for p in product(ALPHABET, repeat=order)]


def build_30mer(guide, flank5=None, flank3=None, pam=None):
    """Assemble the 30mer the way the implementation documents it."""
    left = flank5[-5:] if flank5 and len(flank5) >= 5 else "N" * 5
    right = flank3[:2] if flank3 and len(flank3) >= 2 else "N" * 2
    return left + guide + (pam if pam else "NGG") + right


def one_hot_index(kmer):
    return kmers(len(kmer)).index(kmer)


def test_feature_vector_length():
    feats = doench2016._featurize_guide("GACAGCATCGTACGTTGCAG")
    assert feats.shape == (627,)


def test_single_nucleotide_onehot_layout():
    guide = "GACAGCATCGTACGTTGCAG"
    s = build_30mer(guide, flank5="ACGTACGTAC", flank3="TTGGCCAATT", pam="AGA")
    feats = doench2016._featurize_guide(
        guide, flank_5prime="ACGTACGTAC", flank_3prime="TTGGCCAATT", pam_seq="AGA"
    )

    pd1 = feats[PD1].reshape(30, 4)
    for pos, base in enumerate(s):
        block = pd1[pos]
        assert block.sum() == 1.0, f"position {pos} of {s!r} not one-hot"
        assert block[ALPHABET.index(base)] == 1.0, f"position {pos} encodes {base}"

    counts = np.array([s.count(b) for b in ALPHABET], dtype=float)
    assert feats[PI1] == pytest.approx(counts)
    assert counts.sum() == 30


def test_dinucleotide_onehot_layout():
    guide = "CAATGCTAGCTAGGCATCAT"
    s = build_30mer(guide, flank5="GGCATGCATG", flank3="AGTCGTAGCT", pam="CCA")
    feats = doench2016._featurize_guide(
        guide, flank_5prime="GGCATGCATG", flank_3prime="AGTCGTAGCT", pam_seq="CCA"
    )

    kmers2 = kmers(2)
    pd2 = feats[PD2].reshape(29, 16)
    expected = np.zeros((29, 16))
    for pos in range(29):
        expected[pos, kmers2.index(s[pos:pos + 2])] = 1.0
    assert feats[PD2] == pytest.approx(expected.reshape(-1))

    counts = {k: 0 for k in kmers2}
    for pos in range(29):
        counts[s[pos:pos + 2]] += 1
    assert feats[PI2] == pytest.approx([counts[k] for k in kmers2])


@pytest.mark.parametrize("guide,expected", [
    ("ATATATATATATATATATAT", [0, 1, 0]),     # GC = 0
    ("GCGCGCGCGATATATATATA", [0, 1, 9]),     # GC = 9
    ("AGCTAGCTAGCTAGCTAGCT", [0, 0, 10]),    # GC = 10: boundary, neither flag
    ("GCGCGCGCGCGATATATATA", [1, 0, 11]),    # GC = 11
    ("GCGCGCGCGCGCGCGCGCGC", [1, 0, 20]),    # GC = 20
])
def test_gc_feature_boundaries(guide, expected):
    feats = doench2016._featurize_guide(guide)
    assert feats[GC].tolist() == [float(v) for v in expected]


def test_nggx_feature_uses_guide_end_and_pam_end():
    guide = "GACAGCATCGTACGTTGCAG"  # ends in G
    feats = doench2016._featurize_guide(guide, pam_seq="TCA")  # ends in A
    expected = np.zeros(16)
    expected[one_hot_index("GA")] = 1.0
    assert feats[NGGX] == pytest.approx(expected)


def test_tm_segments_match_documented_slices():
    guide = "TCCAGCTATGACGATTACCA"
    flank5, flank3, pam = "GGCATGCATG", "AGTCGTAGCT", "CCA"
    s = build_30mer(guide, flank5, flank3, pam)
    feats = doench2016._featurize_guide(
        guide, flank_5prime=flank5, flank_3prime=flank3, pam_seq=pam
    )

    from Bio.SeqUtils.MeltingTemp import Tm_NN
    expected = [Tm_NN(s), Tm_NN(s[19:24]), Tm_NN(s[11:19]), Tm_NN(s[6:11])]
    assert feats[TM] == pytest.approx(expected)


def test_missing_flanks_fill_with_n():
    guide = "GACAGCATCGTACGTTGCAG"
    feats_no_flank = doench2016._featurize_guide(guide)
    feats_short_flank = doench2016._featurize_guide(
        guide, flank_5prime="ACG", flank_3prime="T"
    )
    assert feats_no_flank == pytest.approx(feats_short_flank)
    # 5 left N + 2 right N + 1 PAM N (of NGG) contribute no one-hot ones.
    assert feats_no_flank[PD1].sum() == 22.0


def test_flanks_truncate_to_documented_lengths():
    guide = "GACAGCATCGTACGTTGCAG"
    feats_long = doench2016._featurize_guide(
        guide, flank_5prime="ACGTACGTAC", flank_3prime="TTGGCCAATT", pam_seq="AGA"
    )
    feats_exact = doench2016._featurize_guide(
        guide, flank_5prime="CGTAC", flank_3prime="TT", pam_seq="AGA"
    )
    assert feats_long == pytest.approx(feats_exact)


def test_pam_is_used_not_hardcoded_ngg():
    guide = "GACAGCATCGTACGTTGCAG"
    feats_aaa = doench2016._featurize_guide(guide, pam_seq="AAA")
    feats_aga = doench2016._featurize_guide(guide, pam_seq="AGA")
    assert not np.allclose(feats_aaa, feats_aga)

    # Position 25 (first PAM base) must encode A for pam 'AGA'.
    pd1 = feats_aga[PD1].reshape(30, 4)
    assert pd1[25][ALPHABET.index("A")] == 1.0


def test_scores_are_deterministic_and_bounded():
    guides = ["GACAGCATCGTACGTTGCAG", "ATATATATATATATATATAT", "TCCAGCTATGACGATTACCA"]
    first = doench2016.score_guides(guides)
    second = doench2016.score_guides(guides)
    assert first == pytest.approx(second)
    assert np.all(first >= 0.0) and np.all(first <= 1.0)


def test_golden_scores_match_fixture():
    """Replay fixtures/doench2016_scores.tsv through score_guides.

    Regenerate the fixture with fixtures/regenerate_doench2016_scores.py
    only when a scoring change is intentional.
    """
    rows = []
    with open(FIXTURE_PATH) as f:
        for line in f:
            if line.startswith("#"):
                continue
            rows.append(line.rstrip("\n").split("\t"))

    header, data = rows[0], rows[1:]
    assert header == ["variant", "guide", "flank5", "flank3", "pam", "score"]

    guides, flanks, pams, expected = [], [], [], []
    for variant, guide, flank5, flank3, pam, score in data:
        guides.append(guide)
        flanks.append((flank5, flank3))
        pams.append(pam)
        expected.append(float(score))
        assert variant in ("default", "pams", "full")

    # The fixture groups rows by variant, so replay each variant's slice
    # with the same call shape the generator used.
    actual = np.full(len(data), np.nan)
    for variant in ("default", "pams", "full"):
        idx = [i for i, row in enumerate(data) if row[0] == variant]
        if not idx:
            continue
        sub_guides = [guides[i] for i in idx]
        if variant == "default":
            scores = doench2016.score_guides(sub_guides)
        elif variant == "pams":
            scores = doench2016.score_guides(sub_guides, pams=[pams[i] for i in idx])
        else:
            scores = doench2016.score_guides(
                sub_guides, flanks=[flanks[i] for i in idx], pams=[pams[i] for i in idx]
            )
        actual[idx] = scores

    assert actual == pytest.approx(np.array(expected), abs=1e-12)
